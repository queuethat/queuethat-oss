// Compiles supabase/tests/rls/matrix.yaml and supabase/security-definer-allowlist.txt into
// pgTAP (F11, #21). Outputs are committed; CI re-runs this and fails on drift.
//
// A deployment that adds tables of its own (a hosted service) adds a file next to matrix.yaml,
// matrix.<name>.yaml, rather than editing it. Such a file may hold:
//   actors        extra actors, set up by its own tests.create_world_extensions()
//   global_tables, tables   as in matrix.yaml; a table already listed is an error
//   allow_extra   { <table>: { <op>: [actors] } } added to a table listed elsewhere
//
//   supabase/tests/helpers/_generated.psql   allowlists the structural tests read
//   supabase/tests/rls/matrix.test.sql       one assertion per table x actor x operation
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { loadMatrix } from './rls-matrix.mjs';

const root = new URL('../supabase/', import.meta.url).pathname;
const OPS = ['select', 'insert', 'update', 'delete'];
const HEADER =
  '-- GENERATED by scripts/compile-rls-matrix.mjs. Do not edit; run `pnpm db:compile-tests`.\n';

const matrixFiles = readdirSync(`${root}tests/rls`);
const loaded = loadMatrix(matrixFiles, (n) => readFileSync(`${root}tests/rls/${n}`, 'utf8'));
const { tables, globalTables } = loaded;
const ACTORS = loaded.actors;

const allowlist = readFileSync(`${root}security-definer-allowlist.txt`, 'utf8')
  .split('\n')
  .map((l) => l.replace(/#.*/, '').trim())
  .filter(Boolean)
  .map((l) => {
    const [name, flag, ...rest] = l.split(/\s+/);
    if (rest.length || (flag && flag !== 'anon') || !/^\w+\.\w+$/.test(name))
      throw new Error(`Bad allowlist line: "${l}"`);
    return { name, anon: flag === 'anon' };
  });

const errors = [...loaded.errors];
const lit = (s) => `'${String(s).replaceAll("'", "''")}'`;
const arr = (xs) => (xs.length ? `array[${xs.map(lit).join(', ')}]::text[]` : `'{}'::text[]`);

function probeSql(table, op, entry) {
  switch (op) {
    case 'select':
      return `select count(*) from ${table} where ${entry.where}`;
    case 'insert':
      return `with x as (insert into ${table} ${entry.insert} returning 1) select count(*) from x`;
    case 'update':
      return `with x as (update ${table} set ${entry.update} where ${entry.where} returning 1) select count(*) from x`;
    case 'delete':
      return `with x as (delete from ${table} where ${entry.where} returning 1) select count(*) from x`;
  }
}

const assertions = [];
for (const [table, entry] of Object.entries(tables)) {
  if (!/^\w+\.\w+$/.test(table)) errors.push(`${table}: use schema.table`);
  for (const key of ['where', 'update', 'insert', 'allow'])
    if (!entry?.[key]) errors.push(`${table}: missing "${key}"`);
  if (!entry?.allow) continue;
  for (const op of Object.keys(entry.allow))
    if (!OPS.includes(op)) errors.push(`${table}: unknown operation "${op}"`);
  for (const op of OPS) {
    const allowed = entry.allow[op] ?? [];
    for (const a of allowed) {
      if (!ACTORS.includes(a)) errors.push(`${table}.${op}: unknown actor "${a}"`);
      if (a === 'other_owner' && !globalTables.includes(table))
        errors.push(`${table}.${op}: other_owner can never be allowed on a tenant table`);
    }
    for (const actor of ACTORS) {
      const want = allowed.includes(actor) ? 'allow' : 'deny';
      assertions.push(
        `select is(tests.probe(${lit(actor)}, ${lit(probeSql(table, op, entry))}), ${lit(want)}, ${lit(`${table} ${op} as ${actor}: ${want}`)});`,
      );
    }
  }
}

if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}

writeFileSync(
  `${root}tests/helpers/_generated.psql`,
  `${HEADER}
create function tests.definer_allowlist() returns text[]
language sql immutable as $$ select ${arr(allowlist.map((a) => a.name))} $$;

create function tests.anon_definer_allowlist() returns text[]
language sql immutable as $$ select ${arr(allowlist.filter((a) => a.anon).map((a) => a.name))} $$;

create function tests.global_tables() returns text[]
language sql immutable as $$ select ${arr(globalTables)} $$;

create function tests.matrix_tables() returns text[]
language sql immutable as $$ select ${arr(Object.keys(tables))} $$;
`,
);

writeFileSync(
  `${root}tests/rls/matrix.test.sql`,
  `${HEADER}-- Source: supabase/tests/rls/matrix.yaml
begin;
\\ir ../helpers/_setup.psql
select plan(${assertions.length + 1});

select tests.create_world();

select is_empty(
  'select * from tests.tables_without_matrix_entry()',
  'every table in an exposed schema has an entry in supabase/tests/rls/matrix.yaml'
);

${assertions.join('\n')}

select * from finish();
rollback;
`,
);

console.log(
  `Compiled ${Object.keys(tables).length} tables, ${assertions.length} matrix assertions, ${allowlist.length} allowlisted definers.`,
);
